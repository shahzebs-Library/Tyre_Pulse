#!/usr/bin/env python3
"""Build seed/00_reference.sql from the reviewed reference extraction (raw/ref.json).

Only platform configuration is carried: no organisation rows, no user rows, no customer values.
Columns that could name a person (owner, approver, updated_by) were dropped in the extraction query.
system_config: keys are kept; a value is kept only when it is a plain boolean or number; every other
value is replaced by a staging placeholder below.

Usage: build_reference_seed.py <raw_dir> <seed_dir>
"""
import json, os, sys, collections
RAW, OUT = sys.argv[1], sys.argv[2]
rows = json.load(open(os.path.join(RAW, 'ref.json')))
by = collections.OrderedDict()
for r in rows:
    by.setdefault(r['t'], []).append(r['r'])
BUILTIN = {'Admin', 'Manager', 'Director', 'Inspector', 'Reporter', 'Tyre Man', 'Driver'}
for r in by['due_alert_rules']:
    r['recipient_roles'] = [x for x in (r.get('recipient_roles') or []) if x in BUILTIN]
# staging values for system_config
STAGING = {
    'accident_emails_enabled': 'false', 'email_notifications': 'false', 'push_notifications': 'false',
    'workshop_status_push': 'false', 'workshop_status_notifications': 'false', 'upload_gap_push': 'false',
    'ai_enabled': 'false', 'ai_orchestrator_enabled': 'false', 'ai_tyre_inspection_enabled': 'false',
    'backup_enabled': 'false', 'two_factor_required': 'false', 'cron_alert_enabled': 'false',
    'sentry_auto_incidents': 'false', 'user_issue_breach_alerts': 'false',
    'accident_email_to': 'accidents@staging.tyrepulse.invalid', 'accident_email_cc': '',
    'accident_email_subject_prefix': '[STAGING]', 'alert_email': 'alerts@staging.tyrepulse.invalid',
    'support_email': 'support@staging.tyrepulse.invalid', 'company_logo': '', 'default_currency': 'SAR',
    'ai_model': '', 'app_version': 'staging', 'digest_frequency': 'weekly', 'fx_policy': 'monthly_avg',
    'maintenance_message': '', 'report_palette': 'vivid', 'workshop_status_timezone': 'Asia/Riyadh',
    'flutter_latest_version': '', 'mobile_latest_version': '', 'mobile_min_version': '',
}
cfg = []
for r in by.pop('system_config'):
    v = STAGING.get(r['key'], (r['safe_value'] or '').strip('"'))
    cfg.append({'key': r['key'], 'category': r['category'], 'value': v})
out = ['-- Tyre Pulse staging: platform reference rows (configuration only, no customer data).',
       '-- Generated by tools/build_reference_seed.py. See supabase/staging/README.md for the review of each table.',
       'BEGIN;']
def lit(obj):
    return "$ref$" + json.dumps(obj, ensure_ascii=False) + "$ref$::jsonb"
for t, recs in by.items():
    cols = list(recs[0].keys())
    collist = ', '.join('"%s"' % c for c in cols)
    out.append('INSERT INTO public.%s (%s)\nSELECT %s FROM jsonb_populate_recordset(NULL::public.%s, %s)\nON CONFLICT DO NOTHING;'
               % (t, collist, collist, t, lit(recs)))
out.append('-- guard triggers on system_config refuse some keys outside the console; seeding is not a console action\nALTER TABLE public.system_config DISABLE TRIGGER USER;')
out.append("INSERT INTO public.system_config (key, category, value)\nSELECT key, category, value FROM jsonb_to_recordset(%s) AS x(key text, category text, value text)\nON CONFLICT (key) DO UPDATE SET value = excluded.value;" % lit(cfg))
out.append('ALTER TABLE public.system_config ENABLE TRIGGER USER;')
BUCKETS = [('accident-photos', 20971520), ('driver-fine-evidence', 5242880), ('import-files', 104857600),
           ('inspection-photos', 10485760), ('team-action-evidence', 10485760), ('tenant-exports', 52428800),
           ('tyre-photos', 20971520), ('vehicle-photos', 20971520), ('workforce-evidence', 10485760)]
out.append("INSERT INTO storage.buckets (id, name, public, file_size_limit) VALUES\n" +
           ',\n'.join("  ('%s', '%s', false, %d)" % (b, b, n) for b, n in BUCKETS) + "\nON CONFLICT (id) DO NOTHING;")
out.append('COMMIT;')
open(os.path.join(OUT, '00_reference.sql'), 'w').write('\n'.join(out) + '\n')
print({t: len(v) for t, v in by.items()}, 'system_config', len(cfg))
