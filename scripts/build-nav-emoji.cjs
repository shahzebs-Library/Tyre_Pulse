#!/usr/bin/env node
/**
 * Builds public/nav-emoji.svg (one <symbol id="ne-NAME"> per emoji) from
 * src/lib/navEmojiMap.json (route -> Fluent Emoji Flat name).
 *
 * Source set: @iconify-json/fluent-emoji-flat (MIT, Microsoft), not a runtime
 * dependency. Install it in a scratch folder and pass its icons.json:
 *   node scripts/build-nav-emoji.cjs /path/to/@iconify-json/fluent-emoji-flat/icons.json
 * To change an icon: edit navEmojiMap.json, re-run, commit both files.
 */
const fs = require('fs')
const path = require('path')
const iconsPath = process.argv[2]
if (!iconsPath) { console.error('usage: build-nav-emoji.cjs <icons.json>'); process.exit(1) }
const root = path.join(__dirname, '..')
const map = JSON.parse(fs.readFileSync(path.join(root, 'src/lib/navEmojiMap.json'), 'utf8'))
const set = JSON.parse(fs.readFileSync(iconsPath, 'utf8'))
const W = set.width || 32
const H = set.height || 32
const names = [...new Set(Object.values(map))].sort()
const missing = []
const symbols = names.map((n) => {
  const ic = set.icons[n] || (set.aliases?.[n] && set.icons[set.aliases[n].parent])
  if (!ic) { missing.push(n); return '' }
  let body = ic.body
  // Prefix internal ids so two symbols in one sprite can never collide.
  for (const [, id] of body.matchAll(/id="([^"]+)"/g)) {
    body = body.split(`id="${id}"`).join(`id="${n}-${id}"`)
      .split(`url(#${id})`).join(`url(#${n}-${id})`)
      .split(`href="#${id}"`).join(`href="#${n}-${id}"`)
  }
  return `<symbol id="ne-${n}" viewBox="0 0 ${ic.width || W} ${ic.height || H}">${body}</symbol>`
}).join('')
if (missing.length) { console.error('Unknown emoji names:', missing.join(', ')); process.exit(1) }
fs.writeFileSync(path.join(root, 'public/nav-emoji.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink"><!-- Fluent Emoji Flat (MIT, Microsoft) via @iconify-json/fluent-emoji-flat 1.2.6. Generated by scripts/build-nav-emoji.cjs --> ${symbols}</svg>`)
console.log(`${Object.keys(map).length} routes, ${names.length} emoji`)
