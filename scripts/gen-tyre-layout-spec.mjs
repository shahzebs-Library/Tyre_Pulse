#!/usr/bin/env node
/**
 * Generates the Flutter copy of the shared tyre map.
 *
 *   docs/document-specs/tyre-layouts.json  ->  tyre_pulse_flutter/lib/features/
 *                                             tyre_diagram/domain/tyre_layout_spec.g.dart
 *
 * The web reads the JSON directly (src/lib/tyreLayoutSpec.js). Flutter cannot
 * bundle a file from outside its package, so it gets a generated Dart const,
 * and test/features/tyre_diagram/domain/tyre_layout_spec_parity_test.dart
 * fails whenever the two disagree. Run after any change to the JSON:
 *
 *   node scripts/gen-tyre-layout-spec.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const spec = JSON.parse(readFileSync(resolve(root, 'docs/document-specs/tyre-layouts.json'), 'utf8'))
const out = resolve(root, 'tyre_pulse_flutter/lib/features/tyre_diagram/domain/tyre_layout_spec.g.dart')

const s = (v) => `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`
const raw = (v) => `r'${v}'`
const num = (n) => (Number.isInteger(n) ? `${n}.0` : String(n))
const strList = (a) => `<String>[${a.map(s).join(', ')}]`
const strMap = (m) => `<String, String>{${Object.entries(m).map(([k, v]) => `${s(k)}: ${s(v)}`).join(', ')}}`
const argb = (hex) => `0xFF${hex.replace('#', '').toUpperCase()}`

const lines = []
lines.push('// GENERATED by scripts/gen-tyre-layout-spec.mjs from')
lines.push('// docs/document-specs/tyre-layouts.json. DO NOT EDIT BY HAND: change the JSON')
lines.push('// and re-run the script. tyre_layout_spec_parity_test.dart pins the two together.')
lines.push('// ignore_for_file: lines_longer_than_80_chars, prefer_single_quotes')
lines.push('library;')
lines.push('')
lines.push(`const int kTyreSpecVersion = ${spec.version};`)
lines.push(`const String kTyreSpecFallbackLayout = ${s(spec.fallbackLayout)};`)
lines.push('')
lines.push('/// (key, viewH, body, slots[(id, x, y, w, h)]) in render order.')
lines.push('const List<(String, double, String, List<(String, double, double, double, double)>)> kTyreSpecLayouts =')
lines.push('    <(String, double, String, List<(String, double, double, double, double)>)>[')
for (const [key, l] of Object.entries(spec.layouts)) {
  const slots = l.slots.map(([id, x, y, w, h]) => `(${s(id)}, ${num(x)}, ${num(y)}, ${num(w)}, ${num(h)})`).join(', ')
  lines.push(`  (${s(key)}, ${num(l.viewH)}, ${s(l.body)}, <(String, double, double, double, double)>[${slots}]),`)
}
lines.push('];')
lines.push('')
lines.push('const Map<String, Map<int, String>> kTyreSpecAxleVariants = <String, Map<int, String>>{')
for (const [k, v] of Object.entries(spec.axleVariants)) {
  lines.push(`  ${s(k)}: <int, String>{${Object.entries(v).map(([n, key]) => `${n}: ${s(key)}`).join(', ')}},`)
}
lines.push('};')
lines.push('')
lines.push(`const List<String> kTyreSpecTyreless = ${strList(spec.tyreless)};`)
lines.push(`const String kTyreSpecAssetPrefixPattern = ${raw(spec.assetPrefix.pattern)};`)
lines.push(`const Map<String, String> kTyreSpecAssetPrefixMap = ${strMap(spec.assetPrefix.map)};`)
lines.push(`const List<String> kTyreSpecPickupWords = ${strList(spec.pickupModels.words)};`)
lines.push(`const List<String> kTyreSpecPickupCompact = ${strList(spec.pickupModels.compact)};`)
lines.push(`const List<(int, String)> kTyreSpecWheeler = <(int, String)>[${spec.wheeler.map(([n, k]) => `(${n}, ${s(k)})`).join(', ')}];`)
lines.push('')
lines.push('/// (layout, words, compact) - tried top to bottom.')
lines.push('const List<(String, List<String>, List<String>)> kTyreSpecKeywordRules = <(String, List<String>, List<String>)>[')
for (const r of spec.keywordRules) lines.push(`  (${s(r.layout)}, ${strList(r.words || [])}, ${strList(r.compact || [])}),`)
lines.push('];')
lines.push('')
lines.push(`const Map<String, String> kTyreSpecCodesBase = ${strMap(spec.positionCodes.base)};`)
lines.push('')
lines.push('/// (match, scope, codes) - scope "display" is left out of ERP matching.')
lines.push('const List<(List<String>, String, Map<String, String>)> kTyreSpecCodeOverrides = <(List<String>, String, Map<String, String>)>[')
for (const o of spec.positionCodes.overrides) lines.push(`  (${strList(o.match)}, ${s(o.scope)}, ${strMap(o.codes)}),`)
lines.push('];')
lines.push('')
lines.push('const Map<String, Map<String, List<String>>> kTyreSpecAliases = <String, Map<String, List<String>>>{')
for (const [k, m] of Object.entries(spec.positionAliases)) {
  if (k.startsWith('$')) continue
  lines.push(`  ${s(k)}: <String, List<String>>{${Object.entries(m).map(([slot, a]) => `${s(slot)}: ${strList(a)}`).join(', ')}},`)
}
lines.push('};')
lines.push('')
lines.push(`const Map<String, String> kTyreSpecConditionExact = ${strMap(spec.conditions.exact)};`)
lines.push(`const List<String> kTyreSpecConditionOrder = ${strList(spec.conditions.order)};`)
lines.push(`const Map<String, String> kTyreSpecConditionPatterns = <String, String>{${Object.entries(spec.conditions.patterns).map(([k, v]) => `${s(k)}: ${raw(v)}`).join(', ')}};`)
lines.push('/// Phrases that DENY a fault ("no damage") - replaced by "ok" before any test.')
lines.push(`const String kTyreSpecConditionNegation = ${raw(spec.conditions.negation)};`)
lines.push('')
const nums = (a) => `<double>[${a.map(num).join(', ')}]`
const numLists = (a) => `<List<double>>[${(a || []).map(nums).join(', ')}]`
lines.push('/// (kind, band, label, match or empty, strokes, closed, circles, dots) in spec order.')
lines.push('/// Glyphs are on a 24x24 grid; see the `conditions.kinds` comment in the JSON.')
lines.push('const List<(String, String, String, String, List<List<double>>, List<List<double>>, List<List<double>>, List<List<double>>)> kTyreSpecConditionKinds =')
lines.push('    <(String, String, String, String, List<List<double>>, List<List<double>>, List<List<double>>, List<List<double>>)>[')
for (const k of spec.conditions.kinds) {
  const g = k.glyph || {}
  lines.push(`  (${s(k.kind)}, ${s(k.band)}, ${s(k.label)}, ${raw(k.match || '')}, ${numLists(g.strokes)}, ${numLists(g.closed)}, ${numLists(g.circles)}, ${numLists(g.dots)}),`)
}
lines.push('];')
lines.push('')
lines.push(`const List<String> kTyreSpecRiskOrder = ${strList(spec.risk.order)};`)
lines.push(`const Map<String, String> kTyreSpecRiskLabels = ${strMap(spec.risk.labels)};`)
lines.push('/// ARGB colours per theme ("light" / "dark") and band.')
lines.push('const Map<String, Map<String, int>> kTyreSpecPalette = <String, Map<String, int>>{')
for (const [theme, p] of Object.entries(spec.risk.palette)) {
  lines.push(`  ${s(theme)}: <String, int>{${Object.entries(p).map(([b, h]) => `${s(b)}: ${argb(h)}`).join(', ')}},`)
}
lines.push('};')
lines.push('')

writeFileSync(out, lines.join('\n'))
// Keep the file in the shape CI's format check expects. Only this one file.
// The committed file carries a trailing comma on every multi-line collection
// (require_trailing_commas), so format once, add the commas where the
// formatter split a collection, and format again (idempotent).
try {
  execFileSync('dart', ['format', out], { stdio: 'ignore' })
  let formatted = readFileSync(out, 'utf8')
  for (let prev = ''; prev !== formatted;) {
    prev = formatted
    formatted = formatted.replace(/([^,\[{(\s>])\n(\s*[\]})])/g, '$1,\n$2')
  }
  writeFileSync(out, formatted)
  execFileSync('dart', ['format', out], { stdio: 'ignore' })
} catch { console.warn('dart not found: run `dart format` on the generated file') }
console.log(`wrote ${out}`)
