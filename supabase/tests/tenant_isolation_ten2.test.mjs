// TEN-2: Company A's raw upload tables and the pending upload queue must be walled per organisation.
// Policies below are the LIVE expressions (pg_policies, 2026-11-12); tables carry a column subset.
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { ORG_A, ORG_B, USERS, asUser, asService, assertLiveMd5, code, createDb, liveFunction, pendingMigration, written }
  from './fixtures/tenant_isolation_harness.mjs';

const migration = await pendingMigration('20261113101000_ten2_raw_upload_tables_org_wall.sql');
const RAW = ['ksa_country_upload_template_staging', 'ksa_kms', 'uae_kms'];

async function setup() {
  const db = await createDb();
  await db.exec(liveFunction('stamp_import_default_org'));
  await assertLiveMd5(db, ['stamp_import_default_org']);
  for (const t of RAW) {
    await db.exec(`
      create table public.${t} (id bigint generated by default as identity primary key, "Asset name" text, created_at timestamptz not null default now());
      alter table public.${t} enable row level security;
      grant select on public.${t} to authenticated; grant all on public.${t} to service_role;
      create policy ${t}_admin_read on public.${t} for select to public
        using ((select public.is_super_admin()) or (select public.app_is_org_admin()));
      insert into public.${t} ("Asset name") values ('TM001'), ('TM002'), ('TM003');`);
  }
  await db.exec(`
    create table public.pending_uploads (
      id uuid primary key default gen_random_uuid(), batch_id uuid not null default gen_random_uuid(),
      uploaded_by uuid, country text, organisation_id uuid, rows jsonb not null default '[]'::jsonb,
      row_count integer not null default 0, status text not null default 'pending', created_at timestamptz not null default now());
    alter table public.pending_uploads enable row level security;
    grant select, insert, update, delete on public.pending_uploads to authenticated;
    create policy pending_uploads_select on public.pending_uploads for select to authenticated
      using ((uploaded_by = (select auth.uid())) or ((select public.get_my_role()) = any (array['Admin','Manager'])));
    create policy pending_uploads_insert on public.pending_uploads for insert to authenticated
      with check (uploaded_by = (select auth.uid()));
    create policy pending_uploads_update on public.pending_uploads for update to authenticated
      using ((select public.get_my_role()) = 'Admin') with check ((select public.get_my_role()) = 'Admin');
    create policy pending_uploads_delete on public.pending_uploads for delete to authenticated
      using ((select public.get_my_role()) = 'Admin');
    create policy admin_only_delete_guard on public.pending_uploads as restrictive for delete to authenticated
      using (public.app_can_admin_delete());`);
  return db;
}
const n = async (db, t) => (await db.query(`select count(*)::int n from public.${t}`)).rows[0].n;

test('TEN-2 BEFORE: a second tenant Admin reads Company A raw uploads and every pending upload', async () => {
  const db = await setup();
  try {
    for (const t of RAW) {
      assert.equal(await asUser(db, USERS.adminB, () => n(db, t)), 3, `tenant B Admin reads ${t}`);
      assert.equal(await asUser(db, USERS.mgrB, () => n(db, t)), 0, `a Manager does not (why the audit probe saw 0)`);
    }
    // Company A user stages an upload exactly as the web client does: no organisation_id sent.
    await asUser(db, USERS.userA, () => db.query(
      `insert into public.pending_uploads (uploaded_by, country, rows, row_count) values ($1,'KSA','[{"serial":"A1"}]',1)`, [USERS.userA]));
    assert.equal((await db.query('select organisation_id from public.pending_uploads')).rows[0].organisation_id, null,
      'the staged row has no organisation today');
    assert.equal(await asUser(db, USERS.mgrB, () => n(db, 'pending_uploads')), 1, 'tenant B Manager reads the Company A upload');
    assert.equal(await asUser(db, USERS.adminB, () => written(db, `update public.pending_uploads set rows = '[]'`)), 1, 'tenant B Admin rewrites it');
    assert.equal(await asUser(db, USERS.adminB, () => written(db, 'delete from public.pending_uploads')), 1, 'tenant B Admin removes it');
  } finally { await db.close(); }
});

test('TEN-2 AFTER: other tenants read nothing, Company A keeps its rows and its upload paths', async () => {
  const db = await setup();
  try {
    await db.exec(migration);
    await db.exec(migration); // idempotent

    for (const t of RAW) {
      assert.equal((await db.query(`select count(*)::int n from public.${t} where organisation_id = '${ORG_A}'`)).rows[0].n, 3,
        `${t}: every existing row is stamped Company A`);
      assert.equal(await asUser(db, USERS.adminB, () => n(db, t)), 0, `tenant B Admin reads 0 from ${t}`);
      assert.equal(await asUser(db, USERS.mgrB, () => n(db, t)), 0);
      assert.equal(await asUser(db, USERS.superA, () => n(db, t)), 3, `Company A super admin keeps ${t}`);
      assert.equal(await asUser(db, USERS.adminA, () => n(db, t)), 3, `a future plain Company A Admin keeps ${t}`);
      assert.equal(await asUser(db, USERS.mgrA, () => n(db, t)), 0, 'role gate inside the company is unchanged');
      // Table Editor / service role load: no profile, organisation stamped by the existing V290 trigger.
      const { rows } = await asService(db, () => db.query(`insert into public.${t} ("Asset name") values ('TM999') returning organisation_id`));
      assert.equal(rows[0].organisation_id, ORG_A, `${t}: a Table Editor load still lands, stamped Company A`);
    }
    // Multi-tenant mode: an unattributed load is refused (PT409) unless the loader names the organisation.
    await db.exec(`update public.system_config set value = 'false' where key = 'single_tenant_mode'`);
    await assert.rejects(asService(db, () => db.query(`insert into public.uae_kms ("Asset name") values ('X')`)), code('PT409'));
    await db.exec('begin');
    await db.query(`select set_config('tp.import_org', $1, true)`, [ORG_B]);
    await db.exec(`insert into public.uae_kms ("Asset name") values ('B-ONLY')`);
    await db.exec('commit');
    assert.equal(await asUser(db, USERS.adminB, () => n(db, 'uae_kms')), 1, 'tenant B Admin sees only its own row');
    assert.equal(await asUser(db, USERS.superA, () => n(db, 'uae_kms')), 5, 'a super admin sees every organisation');
    assert.equal(await asUser(db, USERS.adminA, () => n(db, 'uae_kms')), 4, 'a plain Company A Admin does not see tenant B');

    // pending_uploads: the client payload is unchanged, the row now carries the uploader's organisation.
    await asUser(db, USERS.userA, () => db.query(
      `insert into public.pending_uploads (uploaded_by, country, rows, row_count) values ($1,'KSA','[{"serial":"A1"}]',1)`, [USERS.userA]));
    assert.equal((await db.query('select organisation_id from public.pending_uploads')).rows[0].organisation_id, ORG_A);
    assert.equal(await asUser(db, USERS.mgrB, () => n(db, 'pending_uploads')), 0, 'tenant B Manager reads 0');
    assert.equal(await asUser(db, USERS.adminB, () => n(db, 'pending_uploads')), 0, 'tenant B Admin reads 0');
    assert.equal(await asUser(db, USERS.adminB, () => written(db, `update public.pending_uploads set rows = '[]'`)), 0, 'and writes 0 rows');
    assert.equal(await asUser(db, USERS.adminB, () => written(db, 'delete from public.pending_uploads')), 0);
    await assert.rejects(asUser(db, USERS.adminB, () => db.query(
      `insert into public.pending_uploads (uploaded_by, organisation_id) values ($1,$2)`, [USERS.adminB, ORG_A])), code('42501'),
      'tenant B cannot plant an upload inside Company A');
    assert.equal((await db.query('select count(*)::int n from public.pending_uploads')).rows[0].n, 1, 'privileged recount: the row survived');
    // Company A reviewers keep working.
    assert.equal(await asUser(db, USERS.mgrA, () => n(db, 'pending_uploads')), 1);
    assert.equal(await asUser(db, USERS.userA, () => n(db, 'pending_uploads')), 1, 'the uploader still sees their own batch');
    assert.equal(await asUser(db, USERS.superA, () => written(db, `update public.pending_uploads set row_count = 1`)), 1);
    assert.equal(await asUser(db, USERS.adminA, () => written(db, 'delete from public.pending_uploads')), 1);
  } finally { await db.close(); }
});

test('TEN-2 migration refuses to run when pending_uploads holds a row with no organisation', async () => {
  const db = await setup();
  try {
    await db.exec(`insert into public.pending_uploads (uploaded_by) values ('${USERS.userA}')`);
    await assert.rejects(db.exec(migration), /TEN-2 aborted: pending_uploads has rows with no organisation/);
  } finally { await db.close(); }
});
