const sha256 = value => createHash('sha256').update(value).digest('hex')
const lineOf = (source, index) => source.slice(0, index).split('\n').length

function classify(page, source, sourcePath) {
  const tables = [...source.matchAll(/<table\b[\s\S]*?<\/table>/gi)]
  const base = {
    page,
    source: sourcePath.replaceAll('\\', '/'),
    sourceSha256: sha256(source),
  }

  if (tables.length === 0) {
    return {
      ...base,
      classification: 'false-positive',
      evidence: ['No current <table> element; the frozen regex inventory is stale or matched non-table text.'],
    }
  }

  const certification = boundedCertifications.get(page)
  if (certification && certification.required.every(fragment => source.includes(fragment))) {
    return {
      ...base,
      classification: 'intentionally-bounded/small',
      evidence: [certification.evidence, `Source anchors: ${certification.required.join(' | ')}`],
    }
  }

  if (/useVirtualizer\s*\(|<EnterpriseTable\b[\s\S]*?\bvirtual(?:=|\s)/.test(source)) {
    return {
      ...base,
      classification: 'virtualized',
      evidence: ['Current source uses a virtualizer or EnterpriseTable virtual mode.'],
    }
  }

  const serverRange = /\.range\s*\([^)]*\)/.test(source)
  const serverWindowArgs = /\blimit\s*:\s*(?:PAGE_SIZE|pageSize|limit)\b/.test(source) &&
    /\boffset\s*:\s*[^,}\n]*(?:page|cursor)/i.test(source)
  if ((serverRange || serverWindowArgs) && /(page|offset|cursor|pageSize|PAGE_SIZE)/i.test(source)) {
    return {
      ...base,
      classification: 'server-paged',
      evidence: ['Current source applies a limit/range plus offset with paging state at the data boundary.'],
    }
  }

  if (/usePagedRows\s*\(|<TablePagination\b|<EnterpriseTable\b/.test(source)) {
    const mechanisms = []
    if (/usePagedRows\s*\(/.test(source)) mechanisms.push('usePagedRows')
    if (/<TablePagination\b/.test(source)) mechanisms.push('TablePagination')
    if (/<EnterpriseTable\b/.test(source)) mechanisms.push('EnterpriseTable')
    return {
      ...base,
      classification: 'client-paged/shared-enterprise-table',
      evidence: [`Current source uses shared paging: ${mechanisms.join(' + ')}.`],
    }
  }

  const hasClientWindow = /\b(?:paginated\w*|pageRows|pagedRows)\b\s*=\s*(?:useMemo\s*\(\s*\(\)\s*=>\s*\{[\s\S]{0,300}?)?[^;\n]*\.slice\s*\(/i.test(source)
  if (hasClientWindow && /\btotalPages\b/.test(source)) {
    return {
      ...base,
      classification: 'client-paged/shared-enterprise-table',
      evidence: ['Current source renders an explicit client page window and computes totalPages.'],
    }
  }

  const dynamicTables = tables.filter(match => /\.map\s*\(|\.flatMap\s*\(/.test(match[0]))
  if (dynamicTables.length === 0) {
    return {
      ...base,
      classification: 'intentionally-bounded/small',
      evidence: [`${tables.length} table(s) render fixed rows without a dynamic row iterator.`],
    }
  }

  const explicitlyBounded = dynamicTables.every(match =>
    /\.slice\s*\(\s*0\s*,\s*\d+\s*\)\s*\.map\s*\(/.test(match[0]) ||
    /\b(?:take|top|recent|preview)(?:Rows|Items|Records)?\b/i.test(match[0]) && /\.slice\s*\(/.test(match[0]),
  )
  if (explicitlyBounded) {
    return {
      ...base,
      classification: 'intentionally-bounded/small',
      evidence: ['Every dynamic table explicitly limits a preview/top/recent collection before rendering.'],
    }
  }

  return {
    ...base,
    classification: 'unsafe/unbounded',
    evidence: dynamicTables.map(match =>
      `Dynamic table at line ${lineOf(source, match.index)} has no proven server, shared-client, virtual, or explicit small bound.`,
    ),
  }
}

async function buildManifest() {
  const inventory = JSON.parse(await readFile(inventoryPath, 'utf8'))
  if (frozenPageNames.length !== 153 || new Set(frozenPageNames).size !== 153) {
    throw new Error(`Frozen baseline must contain 153 unique candidates; found ${frozenPageNames.length}.`)
  }

  const candidates = []
  for (const page of frozenPageNames) {
    const sourcePath = path.join('src', 'pages', `${page}.jsx`)
    let source
    try {
      source = await readFile(path.join(root, sourcePath), 'utf8')
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error
      candidates.push({
        page,
        source: sourcePath.replaceAll('\\', '/'),
        sourceSha256: null,
        classification: 'false-positive',
        evidence: ['The frozen candidate no longer has a page source file at the inventoried path.'],
      })
      continue
    }
    candidates.push(classify(page, source, sourcePath))
  }

  const counts = Object.fromEntries([...allowed].map(category => [category, 0]))
  for (const candidate of candidates) counts[candidate.classification] += 1

  return {
    schemaVersion: 1,
    baseline: 'audit/module-inventory-2026-08-30.json#tableWithoutPagination',
    baselineCandidateCount: frozenPageNames.length,
    currentInventoryCandidateCount: inventory.tableWithoutPagination?.length ?? null,
    generatedBy: 'scripts/classify-table-pagination.mjs',
    methodology: 'Source-evidence classification; ambiguous dynamic tables fail closed as unsafe/unbounded.',
    excludedFromRemediationOwnership: [
      'DataReconciliation',
      'ExpenseImport',
      'MaintenanceCostBoard',
    ],
    counts,
    candidates,
  }
}

function validate(manifest) {
  if (manifest.baselineCandidateCount !== 153 || manifest.candidates.length !== 153) {
    throw new Error('Manifest must classify all 153 frozen candidates exactly once.')
  }
  const pages = new Set()
  for (const candidate of manifest.candidates) {
    if (pages.has(candidate.page)) throw new Error(`Duplicate candidate: ${candidate.page}`)
    pages.add(candidate.page)
    if (!allowed.has(candidate.classification)) throw new Error(`Invalid classification for ${candidate.page}`)
    if (!candidate.evidence?.length) throw new Error(`Missing evidence for ${candidate.page}`)
  }
  const countTotal = Object.values(manifest.counts).reduce((sum, count) => sum + count, 0)
  if (countTotal !== 153) throw new Error(`Classification counts total ${countTotal}, expected 153.`)
}

const next = await buildManifest()
validate(next)
const serialized = `${JSON.stringify(next, null, 2)}\n`

if (process.argv.includes('--check')) {
  const current = await readFile(manifestPath, 'utf8')
  if (current !== serialized) {
    console.error('Table-pagination classification is stale. Run: node scripts/classify-table-pagination.mjs')
    process.exitCode = 1
  } else {
    console.log(`Verified ${next.candidates.length} candidates: ${JSON.stringify(next.counts)}`)
  }
} else {
  await writeFile(manifestPath, serialized)
  console.log(`Classified ${next.candidates.length} candidates: ${JSON.stringify(next.counts)}`)
}
