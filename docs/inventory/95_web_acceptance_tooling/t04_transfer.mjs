import { open, close } from './pw.mjs'
import { go, field, text, snap, pick } from './ui.mjs'
const who = process.argv[2] || 'storekeeper'
const { page, log } = await open(who)
await go(page, 'movements')
const tabs = await page.getByRole('tab').allTextContents()
console.log('tabs:', tabs.join(', '))
const tr = page.getByRole('tab', { name: /Transfers/i })
if (await tr.count()) await tr.first().click(); else await page.getByRole('button', { name: /Transfers/i }).first().click()
await page.waitForTimeout(2000)
await page.getByRole('button', { name: 'New transfer' }).click()
const dlg = page.getByRole('dialog')
const from = field(dlg, 'From')
const fromOpts = await from.locator('option').allTextContents()
console.log('location options for', who, ':', fromOpts.join(' ; '))
await from.selectOption({ label: fromOpts.find((o) => o.includes('WH-A')) })
const to = field(dlg, 'To')
await to.selectOption({ label: (await to.locator('option').allTextContents()).find((o) => o.includes('WH-B')) })
await pick(dlg, 'Stock line', '020164')
await field(dlg, 'Quantity').fill('2')
await dlg.getByRole('button', { name: 'Dispatch', exact: true }).click()
await page.waitForTimeout(3000)
await snap(page, `t04_${who}_dispatched`)
let t = await text(page)
console.log('after dispatch:', t.slice(t.indexOf('New transfer'), t.indexOf('New transfer') + 500))
const rb = page.getByRole('button', { name: 'Receive', exact: true }).first()
await rb.click()
await page.waitForTimeout(1500)
const d2 = page.getByRole('dialog')
await field(d2, 'Received').fill('2')
await d2.getByRole('button', { name: 'Confirm receipt' }).click()
await page.waitForTimeout(3000)
await snap(page, `t04_${who}_received`)
t = await text(page)
console.log('after receive:', t.slice(t.indexOf('New transfer'), t.indexOf('New transfer') + 500))
console.log(log.filter((l) => l.startsWith('http') && !/organisation_configuration|org_branding|country_addresses|subscription|corrective_actions/.test(l)).join('\n'))
await close()
