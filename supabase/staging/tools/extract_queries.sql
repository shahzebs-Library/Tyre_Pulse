-- Read-only generator queries used to extract the baseline from the SOURCE catalog.
-- Catalog tables only (pg_class, pg_proc, pg_policy, ...). No business table is read.
-- Each query was run through the Supabase MCP execute_sql tool; the JSON result of each batch was saved as
-- raw/<name>.json and fed to tools/build_baseline.py. `set local search_path = ''` only makes
-- pg_get_expr and format_type print schema-qualified names; it changes nothing in the database.
-- Schema list used everywhere:
--   ('public','approval_private','private','workforce_internal','ai_tyre_private','anum_integration','administration_imports')
-- Extension-owned objects are excluded with pg_depend.deptype = 'e'.

-- ===== raw/tables.json (one row per table: rn, s, n, rls, frls, d) =====
set local search_path = '';
with t as (
  select c.oid, n.nspname, c.relname, c.relrowsecurity, c.relforcerowsecurity, c.relpersistence, c.reloptions,
         row_number() over (order by n.nspname, c.relname) rn
  from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where c.relkind='r' and n.nspname in (/* schema list */)
    and not exists (select 1 from pg_depend d where d.classid='pg_class'::regclass and d.objid=c.oid and d.deptype='e'))
select t.rn, t.nspname s, t.relname n, t.relrowsecurity rls, t.relforcerowsecurity frls,
  format('CREATE %sTABLE %I.%I (%s)%s;', case when t.relpersistence='u' then 'UNLOGGED ' else '' end, t.nspname, t.relname,
    (select string_agg(E'\n  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
        || case when a.attcollation <> 0 and a.attcollation <> ty.typcollation then ' COLLATE ' || (select quote_ident(cn.nspname)||'.'||quote_ident(co.collname) from pg_collation co join pg_namespace cn on cn.oid=co.collnamespace where co.oid=a.attcollation) else '' end
        || case when a.attgenerated='s' then ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
                when a.attidentity='a' then ' GENERATED ALWAYS AS IDENTITY'
                when a.attidentity='d' then ' GENERATED BY DEFAULT AS IDENTITY'
                when ad.adbin is not null then ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end
        || case when a.attnotnull then ' NOT NULL' else '' end, ',' order by a.attnum)
     from pg_attribute a join pg_type ty on ty.oid=a.atttypid
     left join pg_attrdef ad on ad.adrelid=a.attrelid and ad.adnum=a.attnum
     where a.attrelid=t.oid and a.attnum>0 and not a.attisdropped) || E'\n',
    case when t.reloptions is not null then ' WITH (' || array_to_string(t.reloptions, ', ') || ')' else '' end) d
from t order by t.rn;

-- ===== raw/func1.json .. func5.json (b = 1..5) =====
set local search_path = '';
with f as (
  select p.oid, n.nspname, p.proname, p.prokind, p.proacl, ntile(5) over (order by n.nspname, p.proname, p.oid) b
  from pg_proc p join pg_namespace n on n.oid=p.pronamespace
  where n.nspname in (/* schema list */)
    and not exists (select 1 from pg_depend d where d.classid='pg_proc'::regclass and d.objid=p.oid and d.deptype='e'))
select f.nspname s, f.proname n, f.oid::regprocedure::text sig, f.prokind k, f.proacl::text[] acl,
  pg_get_userbyid((select proowner from pg_proc where oid=f.oid)) o,
  case when f.prokind in ('f','p') then pg_get_functiondef(f.oid) end d
from f where f.b = :b order by f.nspname, f.proname, f.oid;

-- ===== raw/pol1.json .. pol3.json (b = 1..3; includes schema storage) =====
set local search_path = '';
with p as (
  select pl.*, n.nspname, c.relname, ntile(3) over (order by n.nspname, c.relname, pl.polname) b
  from pg_policy pl join pg_class c on c.oid=pl.polrelid join pg_namespace n on n.oid=c.relnamespace
  where n.nspname in (/* schema list */, 'storage'))
select p.nspname s, p.relname t, p.polname n,
  format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;', p.polname, p.nspname, p.relname,
    case when p.polpermissive then 'PERMISSIVE' else 'RESTRICTIVE' end,
    case p.polcmd when 'r' then 'SELECT' when 'a' then 'INSERT' when 'w' then 'UPDATE' when 'd' then 'DELETE' else 'ALL' end,
    case when p.polroles = '{0}' then 'PUBLIC' else (select string_agg(quote_ident(rolname), ', ') from pg_roles where oid = any(p.polroles)) end,
    case when p.polqual is not null then ' USING (' || pg_get_expr(p.polqual, p.polrelid) || ')' else '' end,
    case when p.polwithcheck is not null then ' WITH CHECK (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')' else '' end) d
from p where b = :b order by 1,2,3;

