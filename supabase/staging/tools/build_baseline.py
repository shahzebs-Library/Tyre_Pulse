#!/usr/bin/env python3
"""Turn the raw catalog extraction (JSON batches produced by the generator queries in
tools/extract_queries.sql) into the ordered baseline SQL files.

Usage: build_baseline.py <raw_dir> <baseline_dir> [defer.json]

Input rows hold DDL TEXT ONLY (pg_get_functiondef, pg_get_constraintdef, ...). No table rows.
Statements are separated by a line holding exactly `-- @@` so the loader can run and report them
one by one; to psql that line is an ordinary comment.
"""
import json, os, re, sys, collections

RAW, OUT = sys.argv[1], sys.argv[2]
DEFER = set(json.load(open(sys.argv[3]))) if len(sys.argv) > 3 and os.path.exists(sys.argv[3]) else set()
PROD_REF = 'jhssdmeruxtrlqnwfksc'
STAGING_REF = 'staging-project-ref'
SEP = '\n-- @@\n'
APP_ROLES = {'anon', 'authenticated', 'service_role', 'authenticator', ''}
SCHEMAS = ['approval_private', 'private', 'workforce_internal', 'ai_tyre_private', 'anum_integration',
           'administration_imports', 'backups', 'erp_promote_bak']

def load(name):
    return json.load(open(os.path.join(RAW, name + '.json')))

def scrub(s):
    return s.replace(PROD_REF, STAGING_REF)

def qi(name):
    return name if re.fullmatch(r'[a-z_][a-z0-9_]*', name) and name not in RESERVED else '"' + name.replace('"', '""') + '"'
RESERVED = {'user', 'order', 'group', 'table', 'select', 'position', 'default', 'check', 'column', 'limit',
            'offset', 'references', 'primary', 'unique', 'grant', 'to', 'from', 'where', 'all', 'and', 'or',
            'not', 'null', 'true', 'false', 'end', 'desc', 'asc', 'window', 'analyse', 'analyze', 'any', 'do'}

def write(fname, header, stmts):
    stmts = [scrub(s.strip()) for s in stmts if s and s.strip()]
    path = os.path.join(OUT, fname)
    with open(path, 'w') as f:
        f.write('-- Tyre Pulse staging baseline: ' + header + '\n')
        f.write('-- Generated by supabase/staging/tools/build_baseline.py from a read-only catalog extraction.\n')
        f.write('-- Schema only. Contains no table rows. Do not edit by hand; regenerate.\n')
        f.write(SEP.lstrip('\n'))
        f.write(SEP.join(stmts))
        f.write('\n')
    counts[fname] = len(stmts)

counts = collections.OrderedDict()
tables = load('tables')
funcs = sum((load('func%d' % i) for i in range(1, 6)), [])
pols = sum((load('pol%d' % i) for i in range(1, 4)), [])
misc = load('misc')
by = collections.defaultdict(list)
for r in misc:
    by[r['k']].append(r)

# ---- 01 schemas
st = ['CREATE SCHEMA IF NOT EXISTS %s;' % s for s in SCHEMAS]
write('01_schemas.sql', 'application schemas', st)

# ---- 02 sequences (identity sequences are created by their column)
st = []
owned = []
for r in by['seq']:
    if (r['x'] or '').startswith('i:'):
        continue
    st.append('CREATE SEQUENCE %s.%s AS %s %s;' % (qi(r['s']), qi(r['t']), r['n'], r['d']))
    if (r['x'] or '').startswith('a:'):
        owned.append('ALTER SEQUENCE %s.%s OWNED BY %s;' % (qi(r['s']), qi(r['t']), r['x'][2:]))
write('02_sequences.sql', 'sequences', st)

# ---- 03 functions (bodies are not validated at creation: check_function_bodies = off)
fn_first, fn_late, fn_after_views = [], [], []
view_names = ['%s.%s' % (r['s'], r['t']) for r in by['view']]
for r in funcs:
    if r['k'] not in ('f', 'p') or not r['d']:
        continue
    s = r['d'].rstrip() + ';'
    k = re.match(r'\s*CREATE OR REPLACE (?:FUNCTION|PROCEDURE) ([^\n]+)', s).group(1)[:160]
    head = s.split('AS $', 1)[0]
    if any(re.search(r'\b' + re.escape(v) + r'\b', head) for v in view_names):
        fn_after_views.append(s)
    else:
        (fn_late if k in DEFER else fn_first).append(s)
write('03_functions.sql', 'functions that do not need a table row type', ['SET check_function_bodies = off;'] + fn_first)

# ---- 04 tables
write('04_tables.sql', 'tables (columns, defaults, generated columns, identity)', [r['d'] for r in tables])
write('05_functions_after_tables.sql', 'functions whose signature needs a table row type',
      ['SET check_function_bodies = off;'] + fn_late)

# ---- 06 constraints
order = {'p': 0, 'u': 1, 'x': 2, 'c': 3, 'f': 4}
cons = sorted(by['con'], key=lambda r: (order.get(r['x'], 9), r['s'], r['t'], r['n']))
write('06_constraints.sql', 'primary keys, unique, exclusion, check, then foreign keys',
      ['ALTER TABLE %s.%s ADD CONSTRAINT %s %s;' % (qi(r['s']), qi(r['t']), qi(r['n']), r['d']) for r in cons])

# ---- 07 indexes
write('07_indexes.sql', 'indexes not owned by a constraint', [r['d'] + ';' for r in by['idx']])

# ---- 08 views
vs = []
for r in by['view']:
    opts = (' WITH (%s)' % r['x']) if r['x'] else ''
    kind = 'MATERIALIZED VIEW' if r['n'] == 'm' else 'VIEW'
    vs.append(('%s.%s' % (r['s'], r['t']), 'CREATE %s %s.%s%s AS\n%s' % (kind, qi(r['s']), qi(r['t']), opts, r['d'].rstrip().rstrip(';') + ';')))
# dependency order: a view that reads another view comes after it
vs.sort()
done, ordered = set(), []
while vs:
    progress = False
    for v in list(vs):
        deps = [o[0] for o in vs if o[0] != v[0] and re.search(r'\b' + re.escape(o[0].split('.', 1)[1]) + r'\b', v[1])]
        if not deps:
            ordered.append(v); vs.remove(v); progress = True
    if not progress:
        ordered += vs; break
write('08_views.sql', 'views in dependency order (security_invoker options preserved)', [v[1] for v in ordered])
write('08_views_dependent_functions.sql', 'functions whose signature needs a view row type',
      ['SET check_function_bodies = off;'] + fn_after_views)

# ---- 09 triggers
st = []
for r in by['trg']:
    st.append(r['d'] + ';')
    if r['x'] == 'D':
        st.append('ALTER TABLE %s.%s DISABLE TRIGGER %s;' % (qi(r['s']), qi(r['t']), qi(r['n'])))
write('09_triggers.sql', 'triggers (disabled state preserved)', st)

# ---- 10 row level security switches
st = []
for r in tables:
    if r['rls']:
        st.append('ALTER TABLE %s.%s ENABLE ROW LEVEL SECURITY;' % (qi(r['s']), qi(r['n'])))
    if r['frls']:
        st.append('ALTER TABLE %s.%s FORCE ROW LEVEL SECURITY;' % (qi(r['s']), qi(r['n'])))
write('10_rls_enable.sql', 'row level security switches', st)

# ---- 11 policies
write('11_policies.sql', 'every row level security policy on the application schemas',
      [r['d'] for r in pols if r['s'] != 'storage'])
write('12_storage_policies.sql', 'policies on storage.objects and storage.buckets',
      [r['d'] for r in pols if r['s'] == 'storage'])

# ---- 13 grants
PRIV = {'r': 'SELECT', 'a': 'INSERT', 'w': 'UPDATE', 'd': 'DELETE', 'D': 'TRUNCATE', 'x': 'REFERENCES',
        't': 'TRIGGER', 'X': 'EXECUTE', 'U': 'USAGE', 'C': 'CREATE'}   # 'm' (MAINTAIN) is PG17 only: skipped

def acl_items(text):
    out = []
    for item in (text or '').split('\n'):
        if not item or '=' not in item:
            continue
        grantee, rest = item.split('=', 1)
        privs = rest.split('/')[0].replace('*', '')
        grantee = grantee.strip('"')
        if grantee in APP_ROLES:
            out.append((grantee or 'PUBLIC', [PRIV[p] for p in privs if p in PRIV]))
    return out

st = []
for r in by['nspacl']:
    for g, p in acl_items(r['d']):
        if r['s'] == 'public' and g == 'PUBLIC':
            continue
        if p:
            st.append('GRANT %s ON SCHEMA %s TO %s;' % (', '.join(p), qi(r['s']), g))
identity_seq = {(q['s'], q['t']): q['x'][2:] for q in by['seq'] if (q['x'] or '').startswith('i:')}
for r in by['relacl']:
    kind = 'SEQUENCE' if r['n'] == 'S' else 'TABLE'
    ident = '%s.%s' % (qi(r['s']), qi(r['t']))
    grants = []
    for g, p in acl_items(r['d']):
        if kind == 'SEQUENCE':
            p = [x for x in p if x in ('SELECT', 'UPDATE', 'USAGE')]
        if p:
            grants.append((', '.join(p), g))
    if (r['s'], r['t']) in identity_seq:
        # An identity column names its own sequence; resolve the real name instead of assuming it.
        tbl, col = identity_seq[(r['s'], r['t'])].rsplit('.', 1)
        body = ["  s := pg_get_serial_sequence('%s', '%s');" % (tbl, col.strip('"')),
                "  execute format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated, service_role', s);"]
        body += ["  execute format('GRANT %s ON SEQUENCE %%s TO %s', s);" % (p, g) for p, g in grants]
        st.append('DO $do$ declare s text; begin\n' + '\n'.join(body) + '\nend $do$;')
        continue
    st.append('REVOKE ALL ON %s %s FROM PUBLIC, anon, authenticated, service_role;' % (kind, ident))
    for p, g in grants:
        st.append('GRANT %s ON %s %s TO %s;' % (p, kind, ident, g))
    m = re.search(r'replident=(\w)', r['x'] or '')
    if m and m.group(1) in 'fn' and r['n'] == 'r':
        st.append('ALTER TABLE %s REPLICA IDENTITY %s;' % (ident, 'FULL' if m.group(1) == 'f' else 'NOTHING'))
colgr = collections.defaultdict(lambda: collections.defaultdict(list))
for r in by['attacl']:
    for g, p in acl_items(r['d']):
        for x in p:
            colgr[(r['s'], r['t'], g)][x].append(r['n'])
for (s, t, g), d in sorted(colgr.items()):
    for priv, cols in sorted(d.items()):
        st.append('GRANT %s (%s) ON TABLE %s.%s TO %s;' % (priv, ', '.join(qi(c) for c in cols), qi(s), qi(t), g))
for r in funcs:
    kind = 'PROCEDURE' if r['k'] == 'p' else 'FUNCTION'
    st.append('REVOKE ALL ON %s %s FROM PUBLIC, anon, authenticated, service_role;' % (kind, r['sig']))
    if r['acl'] is None:
        st.append('GRANT EXECUTE ON %s %s TO PUBLIC;' % (kind, r['sig']))
    else:
        for g, p in acl_items('\n'.join(r['acl'])):
            if p:
                st.append('GRANT EXECUTE ON %s %s TO %s;' % (kind, r['sig'], g))
OBJ = {'r': 'TABLES', 'S': 'SEQUENCES', 'f': 'FUNCTIONS'}
for r in by['defacl']:
    if r['t'] != 'postgres' or r['s'] != 'public' or r['n'] not in OBJ:
        continue
    st.append('ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON %s FROM PUBLIC, anon, authenticated, service_role;' % OBJ[r['n']])
    for g, p in acl_items(r['d']):
        if p:
            st.append('ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT %s ON %s TO %s;' % (', '.join(p), OBJ[r['n']], g))
write('13_grants.sql', 'schema, table, column, sequence and function privileges for anon, authenticated, service_role', st)

# ---- 14 misc
st = list(owned)
for r in by['pub']:
    if r['s'] == 'supabase_realtime' and r['t'] == 'public':
        st.append('ALTER PUBLICATION supabase_realtime ADD TABLE %s.%s;' % (qi(r['t']), qi(r['n'])))
for r in by['rolcfg']:
    if r['s'] == 'authenticator':
        for line in (r['d'] or '').split('\n'):
            if line.startswith('pgrst.db_pre_request='):
                st.append("ALTER ROLE authenticator SET pgrst.db_pre_request = '%s';" % line.split('=', 1)[1])
write('14_misc.sql', 'sequence ownership, realtime publication members, PostgREST pre-request hook', st)

json.dump({'files': counts,
           'expected': {'tables': len(tables), 'functions': sum(1 for r in funcs if r['k'] in 'fp'),
                        'policies': len(pols), 'policies_app': sum(1 for r in pols if r['s'] != 'storage'),
                        'constraints': len(by['con']), 'indexes_non_constraint': len(by['idx']),
                        'views': len(by['view']), 'triggers': len(by['trg']),
                        'sequences_standalone': sum(1 for r in by['seq'] if not (r['x'] or '').startswith('i:')),
                        'sequences_total': len(by['seq']),
                        'rls_enabled_tables': sum(1 for r in tables if r['rls'])}},
          open(os.path.join(OUT, 'MANIFEST.json'), 'w'), indent=1)
print(json.dumps(counts))
